		<h1 class="display">Responsible gambling</h1>
		<p class="lede">Pitchside shows statistical estimates about football. It is for people aged 18 and over. It is not advice, it does not take bets, and nothing here is a promise of any result.</p>

		<h2>Keep in mind</h2>
		<ul>
			<li><strong>No model removes the uncertainty.</strong> Our probabilities are estimates and can be wrong. Our own tests show bookmaker prices predict results better than ours, and that following our numbers against bookmaker prices has lost money.</li>
			<li><strong>Only spend what you can afford to lose.</strong> Decide a limit before you start and keep to it.</li>
			<li><strong>Never chase losses.</strong> A run of bad results does not make the next bet more likely to win.</li>
			<li><strong>Do not borrow to gamble</strong>, and do not gamble to fix money problems.</li>
			<li>Take breaks, and use the deposit limits, time-outs and self-exclusion tools that licensed betting sites provide.</li>
		</ul>

		<h2>If gambling is affecting you or someone you know</h2>
		<p>
			Free, confidential help is available. Examples: in the United Kingdom, the National Gambling Helpline on 0808 8020 133 (GamCare); in the United States, 1-800-GAMBLER. If you are elsewhere, your national gambling regulator or health
			service lists local support, and betting sites in your country are required to link to it.
		</p>

		<h2>Age and local law</h2>
		<p>You must be 18 or over, or older where the law of your country requires it, to use Pitchside. Online betting is restricted or prohibited in some places. You are responsible for following the law where you live.</p>
